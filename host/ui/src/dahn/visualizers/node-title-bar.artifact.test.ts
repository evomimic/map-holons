it.each(['holon-inspector', 'load-holons-inspector'])('%s expands Properties locally without changing mode, allocation, selected children or occurrence attention', async name => {
  const source = await readFile(resolve(process.cwd(), `conductora/resources/dahn-visualizers/${name}.js`), 'utf8');
  const Node = (await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`)).default;
  const node: any = document.createElement(defineCustomElementOnce('fixture-local-pane-attention', Node));
  const properties = document.createElement('section'), input = document.createElement('input'); input.value = 'retained edit'; properties.append(input);
  const collection = document.createElement('section'); collection.textContent = 'retained collection';
  node.setContext(selectedTitleContext({ title: 'Holon: Example', childVisualizers: new Map([['properties', properties], ['collections', collection]]) })); document.body.append(node);
  const attention = vi.fn(), restore = vi.fn();
  node.setOccurrenceAttentionHandler(attention); node.setOccurrenceRestorationHandler(restore);
  applyNodePresentation(node, { width: 800, height: 640, presentation: 'inspect' });
  const grant = node.getNodeInspectorAllocation();
  const expandProperties = node.querySelector('[data-pane-attention-control="properties"]');
  expandProperties.click();
  expect(node.dataset.paneAttention).toBe('properties'); expect(node.dataset.inspectorMode).toBe('properties');
  expect(node.getNodeInspectorAllocation()).toEqual(grant);
  expect(node.body.style.gridTemplateColumns).toBe('minmax(0, 1fr)'); expect(node.actionsVisualizer.hidden).toBe(true);
  expect(expandProperties.getAttribute('aria-label')).toBe('Restore Properties pane');
  expandProperties.click(); expect(node.dataset.paneAttention).toBe(''); expect(node.actionsVisualizer.hidden).toBe(false);
  node.setNodeOwnedCollection(collection);
  expect(node.querySelector('[data-pane-attention-control="collection"]')).toBeNull();
  expect(node.dataset.paneAttention).toBe(''); expect(node.dataset.inspectorMode).toBe('collection');
  expect(node.inspectionHeading.hidden).toBe(false); expect(node.propertiesToggle.hidden).toBe(false);
  expect(node.propertiesToggle.disabled).toBe(false);
  expect(node.body.hidden).toBe(true); expect(node.getNodeInspectorAllocation()).toEqual(grant);
  const index = node.collectionTabBar ?? node.collectionsExpand;
  expect(index.hidden).toBe(false); expect(index.inert).toBe(false);
  expect((node.collectionRegion ?? node.collections).dataset.inspectorGroup).toBe('collection');
  expect(node.body.dataset.inspectorGroup).toBe('inspection');
  expect(node.actionsVisualizer.dataset.inspectorGroup).toBe('inspection');
  expect(node.contains(collection)).toBe(true); expect(node.contains(input)).toBe(true); expect(input.value).toBe('retained edit');
  applyNodePresentation(node, { width: 96, height: 640, presentation: 'compact' });
  expect(node.dataset.paneAttention).toBe('');
  applyNodePresentation(node, { width: 800, height: 640, presentation: 'inspect' });
  expect(node.dataset.inspectorMode).toBe('collection'); expect(node.dataset.paneAttention).toBe('');
  expect(attention).not.toHaveBeenCalled(); expect(restore).not.toHaveBeenCalled();
});

