import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { readFile } from 'node:fs/promises';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['holon-inspector', 'load-holons-inspector', 'connections-first-inspector'].map(name => `host/conductora/visualizer-src/${name}.js`),
  outdir: resolve(root, 'host/conductora/resources/dahn-visualizers'),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  banner: { js: '// Generated by npm run build:node-visualizers; edit host/conductora/visualizer-src instead.' },
  write: !check,
});
if (check) {
  for (const file of result.outputFiles) {
    if (await readFile(file.path, 'utf8') !== file.text) throw new Error(`Stale Node artifact: ${file.path}. Run npm run build:node-visualizers and regenerate schema digests.`);
  }
}
