// Generates the Unicode default case-folding table used by string matching operators.
//
// Usage: node scripts/generate-case-folding-table.mjs <path-to-CaseFolding.txt>
//
// The input must be https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt. The Unicode
// version is part of the matching contract, so a file for any other version is rejected
// rather than silently changing matching behavior.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const UNICODE_VERSION = '17.0.0';
const SOURCE_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/CaseFolding.txt`;
const OUTPUT = 'shared_crates/holons_core/src/descriptors/string_matching/case_folding_table.rs';

const sourcePath = process.argv[2];
if (!sourcePath) {
  throw new Error('Usage: node scripts/generate-case-folding-table.mjs <path-to-CaseFolding.txt>');
}
const source = await readFile(sourcePath);
const text = source.toString('utf8');
const firstLine = text.split('\n', 1)[0].trim();
if (firstLine !== `# CaseFolding-${UNICODE_VERSION}.txt`) {
  throw new Error(`Expected CaseFolding-${UNICODE_VERSION}.txt, found header: ${firstLine}`);
}
const sha256 = createHash('sha256').update(source).digest('hex');

// Full default case folding uses the C (common) and F (full) mappings; S (simple) and
// T (Turkic) mappings are outside the contract.
const mappings = new Map();
for (const line of text.split('\n')) {
  const data = line.split('#', 1)[0].trim();
  if (!data) continue;
  const [code, status, mapping] = data.split(';').map(field => field.trim());
  if (status !== 'C' && status !== 'F') continue;
  const codePoint = Number.parseInt(code, 16);
  if (mappings.has(codePoint)) {
    throw new Error(`Duplicate C/F mapping for U+${code}`);
  }
  mappings.set(codePoint, mapping.split(/\s+/).map(hex => Number.parseInt(hex, 16)));
}

const escape = codePoint => `\\u{${codePoint.toString(16).toUpperCase().padStart(4, '0')}}`;
const rows = [...mappings.entries()]
  .sort(([left], [right]) => left - right)
  .map(([codePoint, folded]) => `    ('${escape(codePoint)}', "${folded.map(escape).join('')}"),`);

const output = `// @generated by scripts/generate-case-folding-table.mjs. Do not edit by hand.
//
// Source: ${SOURCE_URL}
// Source sha256: ${sha256}
// Mappings: status C and F only (full default case folding; no S or T mappings).
//
// Derived from Unicode Character Database data, © Unicode, Inc., used under the
// Unicode License v3 (https://www.unicode.org/license.txt).

/// Unicode version whose CaseFolding.txt produced [\`CASE_FOLDING\`].
pub const CASE_FOLDING_UNICODE_VERSION: &str = "${UNICODE_VERSION}";

/// Full default case-folding mappings, sorted by source scalar value for binary search.
#[rustfmt::skip]
pub(super) static CASE_FOLDING: &[(char, &str)] = &[
${rows.join('\n')}
];
`;

await writeFile(fileURLToPath(new URL(`../${OUTPUT}`, import.meta.url)), output);
console.log(`Wrote ${rows.length} mappings to ${OUTPUT}`);
