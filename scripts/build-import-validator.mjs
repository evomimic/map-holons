// Compile the fixed import schema during the build; packaged CSP forbids runtime code generation.
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const schemaText = await readFile(resolve(root, 'host/conductora/resources/bootstrap-import.schema.json'), 'utf8');
if (schemaText !== await readFile(resolve(root, 'host/ui/public/bootstrap-import.schema.json'), 'utf8')) throw new Error('Native and web import schemas differ');
const schema = JSON.parse(schemaText);
const ajv = new Ajv({ allErrors: true, strict: false, code: { esm: true, source: true } });
const validate = ajv.compile(schema);
const result = await build({
  stdin: { contents: standaloneCode(ajv, validate) + `\nexport const schemaJson = ${JSON.stringify(JSON.stringify(schema))};\n`, resolveDir: root },
  bundle: true, platform: 'browser', format: 'esm', target: 'es2022', write: false,
  banner: { js: '// Generated by node scripts/build-import-validator.mjs; do not edit.' },
});
const output = resolve(root, 'host/ui/src/app/services/generated/bootstrap-import-validator.mjs');
const text = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== text) throw new Error('Import validator is stale; run node scripts/build-import-validator.mjs');
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, text);
}
